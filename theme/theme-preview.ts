/**
 * Writes `theme-preview.css`: the library's palettes declared on a `ThemePreview` frame alone, so a
 * page shows its components in dark or light, switched by a native radio, with no script.
 *
 * Each palette is a copy of `tokens.css`'s own blocks, under a selector that matches the frame
 * while that palette's radio is checked: light is the `:root` block plus the accent scale, dark is
 * the same followed by the `.dark` block. Every token is declared on the frame itself, not only the
 * ones `.dark` changes, because a token that reads another through `var()` is resolved where it is
 * declared: one inherited from `:root` would keep the page's values. `color-scheme` is set too, so
 * native controls inside the frame draw in its palette.
 *
 * ```bash
 * deno task --cwd theme generate   # runs this after auto-dark.ts, before generate.ts
 * ```
 *
 * `theme-preview.test.ts` fails when `theme-preview.css` differs from what this writes.
 */

import { blockDeclarations } from "./auto-dark.ts"

/** The attribute on the component's root. */
export const PREVIEW_ATTRIBUTE = "data-theme-preview"
/** The attribute on each radio, valued `dark` or `light`. */
export const CHOICE_ATTRIBUTE = "data-theme-preview-choice"
/** The attribute on the frame the palette is declared on. */
export const FRAME_ATTRIBUTE = "data-theme-preview-frame"

/** The palettes a preview offers. */
export type PreviewTheme = "dark" | "light"

/**
 * The frame while `theme`'s radio is checked. The child combinators keep a preview's radios and
 * rules to its own frame, so a preview nested in another's frame is not switched by the outer one.
 */
export function frameSelector(theme: PreviewTheme): string {
  return `[${PREVIEW_ATTRIBUTE}]:has(> fieldset [${CHOICE_ATTRIBUTE}="${theme}"]:checked) > [${FRAME_ATTRIBUTE}]`
}

/** `tokens.css`'s layer, which the copies sit in too, so an app's unlayered rules still win. */
const LAYER = "@layer theme.preact-tokens"

/** The header of `tokens.css`'s accent-scale block, which declares the scale on `:root`. */
const ACCENT_SUPPORTS =
  "@supports (color: oklch(from red calc(pow(l, 2)) max(0, c * cos(h * 1deg)) calc(h + alpha)))"

const HEADER = `/*
 * GENERATED by theme-preview.ts from tokens.css — do not edit; run \`deno task --cwd theme generate\`.
 *
 * The library's palettes declared on a ThemePreview frame alone, while its Dark or Light radio is
 * checked. Opt-in: an app that renders ThemePreview imports this after tokens.css. README.md →
 * "Theme preview".
 */
`

/** One rule, indented one level inside the layer. */
function rule(selector: string, declarations: readonly string[], depth = 1): string {
  const pad = "  ".repeat(depth)
  return [
    `${pad}${selector} {`,
    ...declarations.map((declaration) => `${pad}  ${declaration};`),
    `${pad}}`,
  ].join("\n")
}

/**
 * The text of `theme-preview.css` for this `tokens.css`.
 *
 * @throws When `tokens.css` lacks its `:root`, `.dark` or accent-scale block.
 */
export function themePreviewCss(tokensCss: string): string {
  const light = blockDeclarations(tokensCss, ":root", [LAYER])
  const dark = blockDeclarations(tokensCss, ".dark", [LAYER])
  const scale = blockDeclarations(tokensCss, ":root", [LAYER, ACCENT_SUPPORTS])
  const both = `${frameSelector("dark")},\n  ${frameSelector("light")}`
  return `${HEADER}
${LAYER} {
${rule(frameSelector("light"), ["color-scheme: light", ...light])}

${rule(frameSelector("dark"), ["color-scheme: dark", ...light, ...dark])}

  ${ACCENT_SUPPORTS} {
${rule(both, scale, 2)}
  }
}
`
}

if (import.meta.main) {
  const tokens = await Deno.readTextFile(new URL("./tokens.css", import.meta.url))
  await Deno.writeTextFile(new URL("./theme-preview.css", import.meta.url), themePreviewCss(tokens))
  console.log("wrote theme-preview.css")
}

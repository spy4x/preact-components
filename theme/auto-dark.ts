/**
 * Writes the auto-dark copies of the dark token blocks — the region between the `auto-dark`
 * markers in `tokens.css` and `ink.css` — from the `.dark` blocks themselves, so the two paths to
 * the dark palette cannot drift apart.
 *
 * A page that cannot count on its bootstrap script running (a booking page built to work without
 * JavaScript) renders `data-theme-auto` on `<html>`. While that marker is there and the system asks
 * for dark, every dark token applies exactly as if `.dark` were on `<html>`: each region holds the
 * same declarations as its `.dark` block, under `@media (prefers-color-scheme: dark)` and the
 * marker's selector, in the same cascade layer. The bootstrap script removes the marker as its first
 * statement, so once it runs the stored or chosen theme decides alone. `preset.css`'s `dark`
 * variant covers the `dark:` utilities the same way.
 *
 * `tokens.css`'s copy also sets `color-scheme: dark`, which the bootstrap script otherwise sets on
 * `<html>`, so native controls and the page's scrollbar draw dark too.
 *
 * ```bash
 * deno task --cwd theme generate   # runs this after accent-scale.ts, then generate.ts
 * ```
 *
 * `auto-dark.test.ts` fails when either file differs from what this writes.
 */

/** The attribute a server renders on `<html>` to opt into the system's dark scheme without JS. */
export const AUTO_DARK_ATTRIBUTE = "data-theme-auto"

/** The region markers around each generated block. */
export const REGION_START = "/* #region auto-dark — generated by auto-dark.ts, do not edit */"
export const REGION_END = "/* #endregion auto-dark */"

/** What one stylesheet's region is generated from. */
export interface AutoDarkSource {
  /** The stylesheet, relative to this module. */
  file: string
  /** The dark block's selector, exactly as the stylesheet writes it. */
  darkSelector: string
  /** The selector the copy is written under, inside the media query. */
  autoSelector: string
  /** Declarations the copy adds before the copied ones. */
  extra: readonly string[]
}

/** The two stylesheets that carry dark tokens. */
export const AUTO_DARK_SOURCES: readonly AutoDarkSource[] = [
  {
    file: "./tokens.css",
    darkSelector: ".dark",
    autoSelector: `[${AUTO_DARK_ATTRIBUTE}]`,
    extra: ["color-scheme: dark"],
  },
  {
    file: "./ink.css",
    darkSelector: '.dark[data-theme="ink"]',
    autoSelector: `[${AUTO_DARK_ATTRIBUTE}][data-theme="ink"]`,
    extra: [],
  },
]

/** One `{ … }` block of a stylesheet, with the headers of the blocks around it. */
interface Block {
  header: string
  ancestors: string[]
  body: string
}

/** `css` without its comments. */
function stripComments(css: string): string {
  return css.replace(/\/\*[\s\S]*?\*\//g, "")
}

/** The index just past the quoted string that starts at `start`. */
function skipString(css: string, start: number): number {
  const quote = css[start]
  let i = start + 1
  while (i < css.length && css[i] !== quote) i += css[i] === "\\" ? 2 : 1
  return i + 1
}

/**
 * Every block of `css` in the order it closes, and the headers of the blocks open at `at`.
 *
 * Enough of a CSS parser for these two files: comments and quoted strings are skipped, and a
 * header is the text since the last `;`, `{` or `}`.
 */
function parse(css: string, at: number): { blocks: Block[]; openAt: string[] } {
  const blocks: Block[] = []
  const stack: { header: string; bodyStart: number }[] = []
  let openAt: string[] | null = null
  let segmentStart = 0
  let i = 0
  while (i < css.length) {
    if (openAt === null && i >= at) openAt = stack.map((entry) => entry.header)
    if (css.startsWith("/*", i)) {
      const end = css.indexOf("*/", i + 2)
      i = end < 0 ? css.length : end + 2
      continue
    }
    const char = css[i]
    if (char === '"' || char === "'") {
      i = skipString(css, i)
      continue
    }
    if (char === "{") {
      stack.push({ header: stripComments(css.slice(segmentStart, i)).trim(), bodyStart: i + 1 })
      segmentStart = i + 1
    } else if (char === "}") {
      const top = stack.pop()
      if (top === undefined) throw new Error("unbalanced braces")
      blocks.push({
        header: top.header,
        ancestors: stack.map((entry) => entry.header),
        body: css.slice(top.bodyStart, i),
      })
      segmentStart = i + 1
    } else if (char === ";") {
      segmentStart = i + 1
    }
    i++
  }
  if (stack.length > 0) throw new Error("unbalanced braces")
  return { blocks, openAt: openAt ?? [] }
}

/** A block body's declarations, without comments, each on one line and without its `;`. */
export function declarationsOf(body: string): string[] {
  const text = stripComments(body)
  if (text.includes("{")) throw new Error("a dark token block holds a nested rule")
  const declarations: string[] = []
  let depth = 0
  let start = 0
  for (let i = 0; i <= text.length; i++) {
    const char = text[i]
    if (char === "(") depth++
    else if (char === ")") depth--
    else if (i === text.length || (char === ";" && depth === 0)) {
      const declaration = text.slice(start, i).replace(/\s+/g, " ").trim()
      if (declaration !== "") declarations.push(declaration)
      start = i + 1
    }
  }
  return declarations
}

/**
 * The region's text for `css`: one media block per `darkSelector` block, wrapped in whichever of
 * that block's layers the region does not already sit in, without the indent of the marker.
 *
 * @throws If the region markers are missing or `darkSelector` has no block.
 */
export function autoDarkRegion(css: string, source: AutoDarkSource): string {
  const start = css.indexOf(REGION_START)
  if (start < 0 || css.indexOf(REGION_END) < start) {
    throw new Error(`${source.file} has no auto-dark region markers`)
  }
  const { blocks, openAt } = parse(css, start)
  const darkBlocks = blocks.filter((block) => block.header === source.darkSelector)
  if (darkBlocks.length === 0) throw new Error(`${source.file} has no ${source.darkSelector} block`)
  return darkBlocks.map((block) => {
    const wrappers = block.ancestors.slice(openAt.length)
    if (block.ancestors.slice(0, openAt.length).join("\n") !== openAt.join("\n")) {
      throw new Error(`the auto-dark region in ${source.file} is not beside ${source.darkSelector}`)
    }
    const declarations = [...source.extra, ...declarationsOf(block.body)]
    const headers = [...wrappers, "@media (prefers-color-scheme: dark)", source.autoSelector]
    const pad = (depth: number) => "  ".repeat(depth)
    return [
      ...headers.map((header, depth) => `${pad(depth)}${header} {`),
      ...declarations.map((declaration) => `${pad(headers.length)}${declaration};`),
      ...headers.map((_, depth) => `${pad(headers.length - 1 - depth)}}`),
    ].join("\n")
  }).join("\n\n")
}

/**
 * `css` with the text between the region markers replaced by {@link autoDarkRegion}, indented to
 * the start marker's own depth, as `deno fmt` indents it.
 */
export function withAutoDark(css: string, source: AutoDarkSource): string {
  const start = css.indexOf(REGION_START)
  const end = css.indexOf(REGION_END)
  const region = autoDarkRegion(css, source)
  const indent = css.slice(css.lastIndexOf("\n", start) + 1, start)
  const block = region.split("\n").map((line) => line === "" ? "" : `${indent}${line}`).join("\n")
  return `${css.slice(0, start + REGION_START.length)}\n${block}\n${indent}${css.slice(end)}`
}

if (import.meta.main) {
  for (const source of AUTO_DARK_SOURCES) {
    const url = new URL(source.file, import.meta.url)
    await Deno.writeTextFile(url, withAutoDark(await Deno.readTextFile(url), source))
  }
  console.log("wrote the auto-dark regions into tokens.css and ink.css")
}
